"""Shared helpers for negotiation agents (tool telemetry, failure handling, fallback estimates)."""

from pathlib import Path
from typing import Any

from lib.schemas import Claim, Scenario
from lib.toolcall import call_tool
from lib.tracing import Tracer


def load_cached_prompt(prompt_path: Path, cache: dict[str, str | None]) -> str:
    """Load system prompt from disk, caching the result in the provided dict."""
    key = str(prompt_path)
    if cache.get(key) is None:
        cache[key] = prompt_path.read_text(encoding="utf-8")
    return cache[key]  # type: ignore[return-value]


def gather_tool_telemetry(
    scenario: Scenario,
    tool_names: list[str],
    tracer: Tracer,
) -> tuple[dict[str, Any], bool, list[str]]:
    """Invoke multiple tools via call_tool, gathering data and tracking failures.

    Args:
        scenario: Disaster Scenario model.
        tool_names: List of tool names to query from the registry.
        tracer: Tracer for logging call lifecycles.

    Returns:
        tuple containing:
        - data: Merged dict of successful tool results and errors.
        - tool_failed: True if any tool call returned ok=False.
        - failed_tools: List of tool names that failed.
    """
    data: dict[str, Any] = {}
    tool_failed = False
    failed_tools: list[str] = []

    for name in tool_names:
        result = call_tool(name, scenario, tracer)
        if result.ok:
            data[name] = result.data
        else:
            tool_failed = True
            failed_tools.append(name)
            data[f"{name}_error"] = result.error

    return data, tool_failed, failed_tools


def get_baseline_fallback_estimate(agent: str, scenario: Scenario) -> tuple[float, str]:
    """Calculate a deterministic baseline estimate and description from scenario data."""
    agent_clean = agent.lower().strip()
    if agent_clean == "medical":
        total_critical = sum(z.critical_patients for z in scenario.zones)
        return float(total_critical), f"{total_critical} critical patients requiring urgent evacuation"

    if agent_clean == "shelter":
        total_stranded = sum(z.stranded for z in scenario.zones)
        return float(total_stranded), f"{total_stranded} stranded residents seeking emergency shelter"

    if agent_clean == "logistics":
        cut_zones = [z for z in scenario.zones if z.road_access < 0.5]
        cut_pop = sum(z.stranded or z.population // 2 for z in cut_zones)
        needed_batches = max(1, len(cut_zones) * 2)
        return float(needed_batches), f"{needed_batches} ration payload batches for {len(cut_zones)} cut-off zones ({cut_pop} people)"

    return 1.0, "1 general relief unit"


def handle_tool_failure(
    claim: Claim,
    agent: str,
    scenario: Scenario,
    tool_failed: bool,
    failed_tools: list[str] | None = None,
) -> Claim:
    """Ensure claim explicitly states uncertainty and offers a fallback_estimate on tool failure.

    Args:
        claim: Pydantic Claim generated by the agent.
        agent: Agent name ('medical', 'shelter', 'logistics').
        scenario: Current disaster Scenario.
        tool_failed: Whether one or more tools failed during telemetry gathering.
        failed_tools: Names of tools that failed.

    Returns:
        Updated Claim with uncertainty and fallback_estimate populated.
    """
    if not tool_failed:
        return claim

    updates: dict[str, Any] = {}

    # 1. State uncertainty explicitly
    if claim.uncertainty is None or claim.uncertainty == 0.0:
        updates["uncertainty"] = 0.5

    # Ensure uncertainty is explicitly stated in justification text
    just_lower = claim.justification.lower()
    if not any(w in just_lower for w in ("uncertain", "unreliable", "unavailable", "telemetry gap", "data gap")):
        tool_msg = f" ({', '.join(failed_tools)})" if failed_tools else ""
        notice = f" [Data uncertainty: telemetry tool failure{tool_msg}; relying on baseline scenario estimates.]"
        updates["justification"] = f"{claim.justification.strip()}{notice}"

    # 2. Offer a fallback_estimate explicitly in fallback_option
    fallback_lower = claim.fallback_option.lower()
    if not any(w in fallback_lower for w in ("fallback estimate", "fallback_estimate")):
        est_val, est_desc = get_baseline_fallback_estimate(agent, scenario)
        fallback_str = f"Fallback estimate: {est_desc} (~{int(est_val)} target count)."
        if claim.fallback_option:
            updates["fallback_option"] = f"{claim.fallback_option.rstrip('.')}. {fallback_str}"
        else:
            updates["fallback_option"] = fallback_str

    if updates:
        return claim.model_copy(update=updates)
    return claim
