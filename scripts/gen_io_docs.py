"""Generate the documented JSON I/O contracts and validate committed samples."""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lib.schemas import (  # noqa: E402
    Claim,
    Hospital,
    Operations,
    Plan,
    Scenario,
    UnresolvedShortfall,
    Zone,
)


def _default(field) -> str:
    if field.is_required():
        return "Required"
    if field.default_factory is not None:
        return f"Optional (default: {field.default_factory.__name__}())"
    return f"Optional (default: `{json.dumps(field.default, ensure_ascii=False)}`)"


def _type(field) -> str:
    return (str(field.annotation)
            .replace("<class '", "")
            .replace("'>", "")
            .replace("lib.schemas.", "")
            .replace("typing.Any", "Any"))


def _model_table(model: type) -> str:
    lines = [f"### `{model.__name__}`", "", "| Field | Type | Required/default | Meaning |", "|---|---|---|---|"]
    for name, field in model.model_fields.items():
        description = field.description or "Description not supplied by the model."
        lines.append(f"| `{name}` | `{_type(field)}` | {_default(field)} | {description} |")
    return "\n".join(lines)


def _sample_block(path: Path, label: str) -> str:
    raw = path.read_text(encoding="utf-8")
    value = json.loads(raw)
    return f"### {label}\n\n```json\n{json.dumps(value, indent=2, ensure_ascii=False)}\n```"


def generate() -> tuple[str, bool]:
    input_path = ROOT / "samples" / "input.json"
    output_path = ROOT / "samples" / "output_full_run.json"
    trace_path = ROOT / "samples" / "trace_full_run.jsonl"

    try:
        input_value = json.loads(input_path.read_text(encoding="utf-8"))
        scenario = Scenario.model_validate(input_value)
    except Exception as exc:
        raise ValueError(f"samples/input.json does not validate as Scenario: {exc}") from exc
    try:
        output_value = json.loads(output_path.read_text(encoding="utf-8"))
        Plan.model_validate(output_value)
    except Exception as exc:
        raise ValueError(f"samples/output_full_run.json does not validate as Plan: {exc}") from exc

    trace_scenario = None
    try:
        for line_number, line in enumerate(trace_path.read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip():
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"samples/trace_full_run.jsonl line {line_number} is invalid JSON: {exc}") from exc
            if event.get("type") == "scenario_loaded":
                trace_scenario = event.get("payload")
                break
    except OSError as exc:
        raise ValueError(f"cannot read samples/trace_full_run.jsonl: {exc}") from exc

    normalized_sample = scenario.model_dump(mode="json")
    trace_matches = trace_scenario == normalized_sample

    models = (Scenario, Zone, Operations, Hospital, Claim, Plan, UnresolvedShortfall)
    sections = [
        "# Input and output definitions",
        "",
        "Generated by `python scripts/gen_io_docs.py` from the Pydantic models in `lib/schemas.py`.",
        "The input contract is `Scenario`; the output contract is `Plan`. Nested models and the separate specialist `Claim` contract are listed in their own tables.",
        "",
        "## Model fields",
        "",
        "\n\n".join(_model_table(model) for model in models),
        "",
        "## Samples",
        "",
        "`samples/input.json` is the seed scenario. `samples/output_full_run.json` and `samples/trace_full_run.jsonl` are the stored full-run artifacts. This command verifies the trace's `scenario_loaded` payload against the input scenario.",
        "`samples/output.json` is an illustrative plan used by schema tests, not a recorded run output.",
        "",
        _sample_block(input_path, "Input sample: `samples/input.json`"),
        "",
        _sample_block(output_path, "Output sample: `samples/output_full_run.json`"),
        "",
    ]
    return "\n".join(sections), trace_matches


def main() -> int:
    destination = ROOT / "docs" / "IO_DEFINITIONS.md"
    try:
        rendered, trace_matches = generate()
    except Exception as exc:
        print(f"I/O documentation generation failed: {exc}", file=sys.stderr)
        return 1
    destination.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Updated {destination.relative_to(ROOT)}")
    if not trace_matches:
        print(
            "I/O documentation generation failed: samples/trace_full_run.jsonl "
            "scenario_loaded payload does not match samples/input.json (or the "
            "trace has no scenario_loaded event). Regenerate the run with "
            "samples/input.json loaded in the app, then download the trace and "
            "final plan.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
